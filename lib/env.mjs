/**
 * Environment discovery for the export benchmark.
 *
 * Everything the report needs in order to be comparable across machines lives
 * here: the hardware fingerprint, the power/thermal preconditions, and the
 * ffmpeg/ffprobe pair used for fixture generation and output verification.
 */
import { execFileSync, execSync } from "node:child_process";
import { chmodSync, existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import os from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
	diskFreeGiB,
	IS_WIN,
	machineFingerprint as platformFingerprint,
	powerState as platformPower,
} from "./platform.mjs";

export const BENCH_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
/**
 * Where to look for a vendored ffmpeg. This benchmark used to live inside the OpenScreen repo
 * and could rely on the LGPL tree built for the compositor; standalone it has to be told.
 * `OSBENCH_OPENSCREEN_REPO` points at a checkout that has one, and everything still falls back
 * to `ffmpeg` on PATH.
 */
export const REPO_ROOT = process.env.OSBENCH_OPENSCREEN_REPO
	? resolve(process.env.OSBENCH_OPENSCREEN_REPO)
	: resolve(BENCH_ROOT, "..");
export const CACHE_DIR = join(BENCH_ROOT, ".cache");
export const RESULTS_DIR = join(BENCH_ROOT, "results");
export const WORK_DIR =
	process.env.OSBENCH_WORK_DIR || join(os.homedir(), "openscreen-export-benchmark");

export const sh = (cmd) =>
	execSync(cmd, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();

const trySh = (cmd, fallback = null) => {
	try {
		return sh(cmd);
	} catch {
		return fallback;
	}
};

/** Deep-search a directory tree for the vendored LGPL ffmpeg prefix built for the compositor. */
function findVendoredFfmpegPrefix() {
	const roots = [join(REPO_ROOT, "crates", "thirdparty")];
	// The tree is gitignored, so it exists only in whichever checkout built it. From a
	// worktree that is the *main* checkout, which `--git-common-dir` points at.
	const commonDir = trySh("git -C " + JSON.stringify(REPO_ROOT) + " rev-parse --git-common-dir");
	if (commonDir) roots.push(join(resolve(REPO_ROOT, commonDir), "..", "crates", "thirdparty"));
	// And sibling worktrees, which is where a freshly built copy usually lands.
	const wtRoot = commonDir
		? join(resolve(REPO_ROOT, commonDir), "..", ".claude", "worktrees")
		: null;
	if (wtRoot && existsSync(wtRoot)) {
		for (const wt of readdirSync(wtRoot)) roots.push(join(wtRoot, wt, "crates", "thirdparty"));
	}
	if (process.env.MAC_FFMPEG_DIR) roots.unshift(dirname(process.env.MAC_FFMPEG_DIR));
	for (const root of roots) {
		if (!existsSync(root)) continue;
		for (const entry of readdirSync(root)) {
			const prefix = join(root, entry);
			const bin = join(prefix, "bin", IS_WIN ? "ffmpeg.exe" : "ffmpeg");
			if (/^ffmpeg-/.test(entry) && existsSync(bin)) return prefix;
		}
	}
	return null;
}

/**
 * The vendored ffmpeg is `--enable-shared` with a *stale* baked-in prefix, and macOS strips
 * DYLD_* across any SIP-protected exec (`/bin/sh`, `/usr/bin/env`). Inheriting the variable
 * therefore never works. A tiny wrapper that exports it inside its own process does, because
 * the stripping only removes what was inherited.
 *
 * The variable is named per platform. Linux's loader reads LD_LIBRARY_PATH and ignores DYLD_*
 * entirely, so the macOS spelling produced a wrapper that ran and then failed to resolve the
 * very libraries it exists to point at — the shared-library error would name ffmpeg, not this.
 */
function writeLibraryPathWrapper(name, binary, libDir) {
	mkdirSync(CACHE_DIR, { recursive: true });
	const wrapper = join(CACHE_DIR, name);
	const varName = process.platform === "darwin" ? "DYLD_LIBRARY_PATH" : "LD_LIBRARY_PATH";
	writeFileSync(
		wrapper,
		`#!/bin/sh\n# generated by benchmark/lib/env.mjs — see AGENTS.md / macos-dev-toolchain\nexport ${varName}="${libDir}"\nexec "${binary}" "$@"\n`,
	);
	chmodSync(wrapper, 0o755);
	return wrapper;
}

let cachedFfmpeg = null;

/** Resolve an (ffmpeg, ffprobe) pair, preferring an explicit override, then PATH, then vendored. */
export function resolveFfmpeg() {
	if (cachedFfmpeg) return cachedFfmpeg;

	if (process.env.OSBENCH_FFMPEG && process.env.OSBENCH_FFPROBE) {
		cachedFfmpeg = {
			ffmpeg: process.env.OSBENCH_FFMPEG,
			ffprobe: process.env.OSBENCH_FFPROBE,
			source: "env:OSBENCH_FFMPEG",
		};
		return cachedFfmpeg;
	}

	const which = IS_WIN ? "where" : "command -v";
	const onPath = trySh(`${which} ffmpeg`)?.split("\n")[0]?.trim() || null;
	const probeOnPath = trySh(`${which} ffprobe`)?.split("\n")[0]?.trim() || null;
	if (onPath && probeOnPath) {
		cachedFfmpeg = { ffmpeg: onPath, ffprobe: probeOnPath, source: "PATH" };
		return cachedFfmpeg;
	}

	if (IS_WIN) {
		// The repo vendors ffmpeg for the compositor on Windows too; scripts/fetch-ffmpeg.mjs
		// puts it under crates/thirdparty. No wrapper is needed — Windows has no DYLD stripping.
		const prefix = findVendoredFfmpegPrefix();
		if (prefix) {
			cachedFfmpeg = {
				ffmpeg: join(prefix, "bin", "ffmpeg.exe"),
				ffprobe: join(prefix, "bin", "ffprobe.exe"),
				source: `vendored:${prefix}`,
			};
			return cachedFfmpeg;
		}
		throw new Error(
			"No ffmpeg/ffprobe found. Install one on PATH (winget install Gyan.FFmpeg), " +
				"or set OSBENCH_FFMPEG and OSBENCH_FFPROBE.",
		);
	}

	const prefix = findVendoredFfmpegPrefix();
	if (prefix) {
		const lib = join(prefix, "lib");
		cachedFfmpeg = {
			ffmpeg: writeLibraryPathWrapper("ffmpeg", join(prefix, "bin", "ffmpeg"), lib),
			ffprobe: writeLibraryPathWrapper("ffprobe", join(prefix, "bin", "ffprobe"), lib),
			source: `vendored:${prefix}`,
		};
		return cachedFfmpeg;
	}

	throw new Error(
		"No ffmpeg/ffprobe found. Install one on PATH, or set OSBENCH_FFMPEG and OSBENCH_FFPROBE, " +
			"or build the repo's LGPL tree (see benchmark/README.md § ffmpeg).",
	);
}

export function ffmpegVersion() {
	const { ffmpeg, source } = resolveFfmpeg();
	const line = execFileSync(ffmpeg, ["-hide_banner", "-version"], { encoding: "utf8" })
		.split("\n")[0]
		.trim();
	return { banner: line, source };
}

/** Everything about the host that can move a number in the results table. */
export function machineFingerprint() {
	return platformFingerprint();
}

/**
 * Preconditions that silently skew an export benchmark: battery power caps the SoC, a
 * power-saver plan caps it harder, and an already-throttled machine reports whatever the
 * previous run left behind.
 */
export function powerState() {
	return platformPower();
}

/** Free space on the volume that will hold the fixture and every export. */
export function diskState(path = WORK_DIR) {
	return diskFreeGiB(path);
}

export function ensureWorkDirs() {
	for (const d of [
		WORK_DIR,
		CACHE_DIR,
		RESULTS_DIR,
		join(WORK_DIR, "fixture"),
		join(WORK_DIR, "out"),
		join(WORK_DIR, "projects"),
		join(WORK_DIR, "installers"),
	]) {
		mkdirSync(d, { recursive: true });
	}

	// Keep the operating system out of the work directory.
	//
	// A benchmark that exports video fills this tree with gigabytes of it, and macOS then indexes
	// what it finds: `mediaanalysisd` was measured here at 125% of a core while a run was in
	// flight, against 12 GB of the benchmark's own output. That is a confound the harness creates
	// for itself, it grows with every run, and it lands on whichever tool happens to be measured
	// while the daemon is busy. `.metadata_never_index` is the documented way to opt a directory
	// out; Windows has no equivalent problem because nothing analyses video on write.
	if (!IS_WIN) {
		const marker = join(WORK_DIR, ".metadata_never_index");
		if (!existsSync(marker)) writeFileSync(marker, "");
	}
	return { WORK_DIR, CACHE_DIR, RESULTS_DIR };
}
